import { getIndex } from "../retrieval/store";
import { retrieve } from "../retrieval/hybrid";
import { buildCitations, countMarkers, findMarkers } from "./citations";
import { detectContradictions, filterContradictions } from "./contradictions";
import { composeExtractive } from "./extractive";
import { claudeConfigured, generateWithClaude } from "./claude";
import { REFUSAL_SENTENCE } from "./prompt";
import type {
  AnswerBlock,
  AskResult,
  Citation,
  Contradiction,
  Guardrail,
  RetrievalTrace,
  RetrievedChunk,
} from "../types";

export const MAX_QUESTION_LENGTH = 400;

export function sanitizeQuestion(input: unknown): string | null {
  if (typeof input !== "string") return null;
  const cleaned = input.replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim();
  if (cleaned.length < 3 || cleaned.length > MAX_QUESTION_LENGTH) return null;
  return cleaned;
}

export type PreparedAnswer = {
  question: string;
  sources: RetrievedChunk[];
  citations: Citation[];
  contradictions: Contradiction[];
  trace: RetrievalTrace;
};

export async function prepareAnswer(question: string): Promise<PreparedAnswer> {
  const index = getIndex();
  const { sources, trace } = await retrieve(index.chunks, question);
  const citations = buildCitations(sources);
  const contradictions = trace.refusal ? [] : filterContradictions(question, detectContradictions(sources, citations));
  return { question, sources, citations, contradictions, trace };
}

function countValidMarkers(text: string, citations: Citation[]): { total: number; valid: number; invalid: string[] } {
  const markers = findMarkers(text);
  const validMarkers = markers.filter((marker) => citations.some((citation) => citation.marker === marker));
  const invalid = markers.filter((marker) => !validMarkers.includes(marker));
  const total = countMarkers(text);
  let valid = 0;
  for (const match of text.matchAll(/\[(S\d+)\]/g)) {
    const marker = match[1];
    if (marker !== undefined && validMarkers.includes(marker)) valid += 1;
  }
  return { total, valid, invalid };
}

function guardrailFor(blocks: AnswerBlock[], citations: Citation[], note: string | null): Guardrail {
  const text = blocks
    .map((block) => `${block.text ?? ""} ${(block.items ?? []).join(" ")}`)
    .join(" ");
  const { total, valid, invalid } = countValidMarkers(text, citations);
  return {
    citationsChecked: true,
    citationsTotal: total,
    citationsValid: valid,
    invalidMarkers: invalid,
    note,
  };
}

export async function composeAnswer(prepared: PreparedAnswer): Promise<AskResult> {
  const { question, sources, citations, contradictions, trace } = prepared;

  if (trace.refusal) {
    const blocks: AnswerBlock[] = [
      { kind: "direct", text: REFUSAL_SENTENCE },
      {
        kind: "note",
        text: `No retrieved chunk cleared the grounding threshold (confidence ${trace.confidence.toFixed(2)}, coverage ${trace.coverage.toFixed(2)}). The assistant refuses rather than guess.`,
      },
    ];
    return {
      question,
      mode: "refusal",
      answer: { blocks, citations },
      sources,
      trace,
      contradictions,
      guardrail: {
        citationsChecked: false,
        citationsTotal: 0,
        citationsValid: 0,
        invalidMarkers: [],
        note: "Generation skipped: retrieval did not support an answer.",
      },
    };
  }

  if (claudeConfigured()) {
    const generated = await generateWithClaude(question, sources, citations);
    if (generated.ok) {
      const { total, valid, invalid } = countValidMarkers(generated.text, citations);
      if (total > 0 && invalid.length === 0) {
        return {
          question,
          mode: "claude",
          answer: { blocks: generated.blocks, citations },
          sources,
          trace,
          contradictions,
          guardrail: {
            citationsChecked: true,
            citationsTotal: total,
            citationsValid: valid,
            invalidMarkers: [],
            note: `Generated by ${generated.model}; every citation marker matched a retrieved chunk.`,
          },
        };
      }
      console.warn("groundtruth: Claude citations failed validation", invalid);
    } else {
      console.warn("groundtruth: Claude generation failed", generated.error);
    }

    const blocks = composeExtractive(question, sources, citations, contradictions);
    return {
      question,
      mode: "extractive",
      answer: { blocks, citations },
      sources,
      trace,
      contradictions,
      guardrail: guardrailFor(
        blocks,
        citations,
        generated.ok
          ? "Generation rejected: the answer cited a chunk that was not retrieved. Served quoted evidence instead."
          : "Generation provider unavailable. Served quoted evidence instead.",
      ),
    };
  }

  const blocks = composeExtractive(question, sources, citations, contradictions);
  return {
    question,
    mode: "extractive",
    answer: { blocks, citations },
    sources,
    trace,
    contradictions,
    guardrail: guardrailFor(blocks, citations, "No LLM configured: answer assembled from quoted sentences."),
  };
}

export async function ask(question: string): Promise<AskResult> {
  const prepared = await prepareAnswer(question);
  return composeAnswer(prepared);
}
